from datetime import datetime
from src.core.schema import MoCloPart

def generate_genbank_file(
    locus_name: str,
    parts: list[MoCloPart],
    full_sequence: str
) -> str:
    """
    Generates a standardized GenBank flat file representation of the compiled construct.
    """
    seq_length = len(full_sequence)
    date_str = datetime.now().strftime("%d-%b-%Y").upper()

    header = (
        f"LOCUS       {locus_name[:16]:<16} {seq_length:>8} bp    DNA     circular SYN {date_str}\n"
        f"DEFINITION  Level 1 MoClo assembly generated by CLASP-Copilot.\n"
        f"ACCESSION   CLASP_{locus_name}\n"
        f"VERSION     1.0\n"
        f"KEYWORDS    MoClo; Synthetic Biology; Golden Gate; CLASP.\n"
        f"FEATURES             Location/Qualifiers\n"
    )

    features = ""
    current_pos = 1

    for part in parts:
        part_len = len(part.sequence)
        start = current_pos
        end = current_pos + part_len - 1
        
        features += (
            f"     misc_feature    {start}..{end}\n"
            f"                     /label=\"{part.part_id}\"\n"
            f"                     /note=\"Overhangs: 5'={part.overhang_5prime}, 3'={part.overhang_3prime}\"\n"
        )
        current_pos += part_len

    # Format sequence in standard GenBank 60-bp per line, 10-bp block format
    seq_str = full_sequence.lower()
    formatted_seq = "ORIGIN\n"
    for i in range(0, seq_length, 60):
        chunk = seq_str[i:i+60]
        blocks = [chunk[j:j+10] for j in range(0, len(chunk), 10)]
        formatted_seq += f"{i+1:>9} " + " ".join(blocks) + "\n"
    formatted_seq += "//\n"

    return header + features + formatted_seq